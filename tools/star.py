"""The Excellent star — one construction, every output.

Traced from brand/source/star-original.png (low-res raster) and idealised:
  7 rays at exact 360/7° spacing, inner (valley) radius 0.386 of the short rays,
  one ray 1.31× longer, pointing east. Measured deviation of the original from this
  construction: < 3 % on every vertex, i.e. blur, not design.

    .venv/bin/python tools/star.py    # → brand/star*.svg, sources/glyphs-brand*.txt
"""
from __future__ import annotations

import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAYS, INNER, LONG, LONG_AT = 7, 0.386, 1.31, 0  # LONG_AT: index of the long ray (0 = east)


def vertices(rot_deg: float = 0.0) -> list[tuple[float, float]]:
    """14 vertices (tip, valley, …), y-down, centred on the origin."""
    out = []
    for i in range(RAYS):
        a = math.radians(rot_deg + i * 360 / RAYS)
        r = LONG if i == LONG_AT else 1.0
        out.append((r * math.cos(a), r * math.sin(a)))
        b = a + math.pi / RAYS
        out.append((INNER * math.cos(b), INNER * math.sin(b)))
    return out


def bbox(v):
    xs, ys = [p[0] for p in v], [p[1] for p in v]
    return min(xs), min(ys), max(xs), max(ys)


def svg(v=None, pad=0.0) -> str:
    v = v or vertices()
    x0, y0, x1, y1 = bbox(v)
    d = "M" + " L".join(f"{x - x0 + pad:.4f} {y - y0 + pad:.4f}" for x, y in v) + "Z"
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {x1 - x0 + 2 * pad:.4f} {y1 - y0 + 2 * pad:.4f}">'
            f'<path fill="currentColor" d="{d}"/></svg>')


def inside(v, x, y) -> bool:
    c, n = False, len(v)
    for i in range(n):
        (xa, ya), (xb, yb) = v[i], v[i - 1]
        if (ya > y) != (yb > y) and x < (xb - xa) * (y - ya) / (yb - ya) + xa:
            c = not c
    return c


def grid_rows(width_hu: int, n_rows: int, half: bool, thresh=0.3, ss=6) -> list[str]:
    """Rasterise the star into the font's row grid: n_rows rows (or half rows) × width_hu columns.
    Row bands are evenly spaced; the physical aspect (hu = 14u, row = 120u) is respected."""
    v = vertices()
    x0, y0, x1, y1 = bbox(v)
    row_u = 60 if half else 120
    phys_w, phys_h = width_hu * 14, n_rows * row_u
    sw, sh = (x1 - x0), (y1 - y0)
    k = min(phys_w / sw, phys_h / sh)  # fit, preserving the star's aspect
    ox, oy = (phys_w - sw * k) / 2, (phys_h - sh * k) / 2
    rows = []
    for r in range(n_rows):
        line = ""
        for c in range(width_hu):
            hits = 0
            for i in range(ss):
                for j in range(ss):
                    px = (c + (i + .5) / ss) * 14
                    py = (r + (j + .5) / ss) * row_u
                    hits += inside(v, (px - ox) / k + x0, (py - oy) / k + y0)
            line += "#" if hits / ss ** 2 >= thresh else "."
        rows.append(line)
    return rows


def glyph_block(name, unis, width_hu):
    head = f"@ {name} {' '.join(f'U+{u:04X}' for u in unis)} src=brand vector=star"
    return head + "\n| " + "." * width_hu + "\n"


def main():
    out = ROOT / "brand"
    out.mkdir(exist_ok=True)
    (out / "star.svg").write_text(svg())
    note = ("# GENERATED by tools/star.py — do not edit by hand.\n"
            "# The Excellent star: the true vector outline, sliced by the font's scanline rows at build time.\n"
            "# The empty row only sets the glyph width (hu). ★ U+2605 and private-use U+E000.\n\n")
    (ROOT / "sources" / "glyphs-brand.txt").write_text(note + glyph_block("uni2605", [0x2605, 0xE000], 38))
    (ROOT / "sources" / "glyphs-brand-proportional.txt").write_text(note + glyph_block("uni2605", [0x2605, 0xE000], 58))
    print("star →", out / "star.svg")


if __name__ == "__main__":
    main()
